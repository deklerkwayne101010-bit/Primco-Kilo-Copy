// Maps camelCase Product fields to snake_case database columns
export const productToDb = (product: any) => ({
  sku: product.sku,
  name: product.name,
  category: product.category,
  category_code: product.categoryCode,
  category_name: product.categoryName,
  subcategory: product.subcategory,
  subcategory_code: product.subcategoryCode,
  subcategory_name: product.subcategoryName,
  range: product.range,
  range_name: product.rangeName,
  unit: product.unit,
  description: product.description,
  brand: product.brand,
  demo: product.demo,
  featured: product.featured,
  in_stock: product.inStock,
  specs: product.specs,
  image_alt: product.imageAlt,
  badge: product.badge,
  image_url: product.imageUrl
});

export const dbToProduct = (row: any) => ({
  id: row.id,
  sku: row.sku,
  name: row.name,
  category: row.category,
  categoryCode: row.category_code,
  categoryName: row.category_name,
  subcategory: row.subcategory,
  subcategoryCode: row.subcategory_code,
  subcategoryName: row.subcategory_name,
  range: row.range,
  rangeName: row.range_name,
  unit: row.unit,
  description: row.description,
  brand: row.brand,
  demo: row.demo,
  featured: row.featured,
  inStock: row.in_stock,
  specs: row.specs,
  imageAlt: row.image_alt,
  badge: row.badge,
  imageUrl: row.image_url,
  created_at: row.created_at,
  updated_at: row.updated_at
});
